import re
import subprocess
import sys
import xml.etree.ElementTree as ET
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
xml_path = ROOT / "docs" / "evidence" / "junit.xml"
subprocess.run([sys.executable, "-m", "pytest", "-q", f"--junitxml={xml_path}"], cwd=ROOT, check=False,
               stdout=subprocess.DEVNULL)
suite = ET.parse(xml_path).getroot()
rows = []
for case in suite.iter("testcase"):
    name = case.get("name")
    status = "FAIL" if case.find("failure") is not None or case.find("error") is not None else "PASS"
    file = case.get("classname").split(".")[-1]
    base = re.sub(r"\[.*\]", "", name)
    param = re.search(r"\[(.*)\]", name)
    objective = base.removeprefix("test_").replace("_", " ").capitalize() + (f" (input: {param.group(1)})" if param else "")
    rows.append((file, name, objective, status, float(case.get("time"))))
lines = ["# Automated test results (generated)", "", f"Generated by `scripts/gen_test_report.py` from `docs/evidence/junit.xml`.",
         f"Total: {len(rows)}; passed: {sum(r[3] == 'PASS' for r in rows)}; failed: {sum(r[3] == 'FAIL' for r in rows)}.", "",
         "| ID | File | Test function | Objective (from the test name) | Result | Time (s) |", "|---|---|---|---|---|---|"]
for index, (file, name, objective, status, seconds) in enumerate(rows, 1):
    lines.append(f"| T{index:03d} | {file}.py | `{name}` | {objective} | {status} | {seconds:.3f} |")
(ROOT / "docs" / "test_results_generated.md").write_text("\n".join(lines) + "\n")
print("\n".join(lines[:5]))
